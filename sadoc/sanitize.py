"""Keep internal details out of pull requests.

Most of these repositories are public, so a PR must not advertise the tooling
behind it. The full record (model, agent transcript, verification output) stays
in the local SQLite database; the PR carries only a short reference id.

Two jobs:

  1. `scrub_text` - remove tool/model mentions from prose that is about to be
     published (commit messages, PR bodies, agent notes).
  2. `scan_diff` - catch the same markers in *source files* the agent edited,
     where a stray comment like "updated by the bot" would be a real leak.
"""

from __future__ import annotations

import re

# (pattern, marker name for reporting, replacement used when scrubbing).
#
# Phrases come first: removing a whole clause reads far better than replacing a
# word inside it. The replacement is deliberately bland - a dependency update
# written by hand simply would not mention any of this.
LEAK_MARKERS: list[tuple[str, str, str]] = [
    # whole clauses
    (
        r"\b(?:re)?generated by (?:an? |the )?(?:ai|bot|tool|agent|assistant|model|llm)\b",
        "generated automatically",
        "",
    ),
    (
        r"\bupdated by (?:an? |the )?(?:ai|bot|tool|agent|assistant|model|llm)\b",
        "updated automatically",
        "",
    ),
    (r"\bby (?:an? |the )?(?:agent|assistant)\b", "the agent", ""),
    (r"\b(?:the )?(?:agent|assistant|model)'s\b", "the agent", ""),
    (r"\bas (?:instructed|requested|directed) by\b", "instruction", ""),
    (r"\bco[- ]authored[- ]by\b", "co-authored-by", ""),
    (r"\b(?:auto|ai)[- ]generated\b", "generated automatically", ""),
    (r"\bwith the help of\b", "the help of", ""),
    # bare mentions
    (r"\bthe (?:agent|assistant)\b", "the agent", "the change"),
    (r"\bthe model\b", "the model", "the change"),
    (r"\bthe (?:local |open[- ]source )?llm\b", "the model", "the change"),
    (r"\b(?:an?|the) (?:large )?language model\b", "the model", "the change"),
    (r"\bdeps[-_ ]?bot\b", "deps-bot", ""),
    # The tool's own name must never reach a pull request.
    (r"\bsadoc\b", "sadoc", ""),
    (r"\bclaude\b", "claude", ""),
    (r"\bgpt[- ]?\d", "gpt", ""),
    (r"\bqwen[\w.\-]*", "qwen", ""),
    (r"\bllama[\w.\-]*", "llama", ""),
    (r"\bminimax\b", "minimax", ""),
    (r"\bdeepseek\b", "deepseek", ""),
    (r"\bgemma[\w.\-]*", "gemma", ""),
    (r"\bflint\b", "flint", ""),
    (r"\bopenai\b", "openai", ""),
    (r"\banthropic\b", "anthropic", ""),
    (r"\bollama\b", "ollama", ""),
    (r"\bvllm\b", "vllm", ""),
    (r"\bopenrouter\b", "openrouter", ""),
    (r"\bbubblewrap\b|\bbwrap\b", "the sandbox", ""),
    (r"\bsandboxed?\b", "the sandbox", ""),
]

_COMPILED = [
    (re.compile(pattern, re.IGNORECASE), marker, replacement)
    for pattern, marker, replacement in LEAK_MARKERS
]

# Lines that are comments in the languages we touch.
_COMMENT_PREFIXES = ("//", "#", "*", "/*", "--", "<!--")


def scrub_text(text: str, filler: str = "") -> str:
    """Remove tool/model mentions from prose.

    `filler` replaces the match; when it is empty the whole phrase is dropped.
    """
    if not text:
        return text
    out = text
    for pattern, _marker, replacement in _COMPILED:
        out = pattern.sub(replacement, out)
    # Tidy up the damage, but never touch technical punctuation: "vi.fn()" must
    # survive scrubbing intact.
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\s+([,.;:!?])", r"\1", out)
    out = re.sub(r"\(\s+", "(", out)
    out = re.sub(r"\s+\)", ")", out)
    out = re.sub(r"\[\s+", "[", out)
    out = re.sub(r"\s+\]", "]", out)
    out = re.sub(r"^\s*[-*]\s*$", "", out, flags=re.MULTILINE)
    out = re.sub(r"\n{3,}", "\n\n", out)
    return out.strip()


def contains_leak(text: str) -> bool:
    """Does the text still mention any of the tooling?"""
    if not text:
        return False
    return any(pattern.search(text) for pattern, _m, _r in _COMPILED)


def scan_diff(diff: str) -> list[dict]:
    """Find leak markers in a unified diff.

    Returns one record per offending added line, with the marker that matched
    and whether the line looks like a comment (removable) or real code.
    """
    hits: list[dict] = []
    current_file = None
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            current_file = line[6:]
            continue
        if not line.startswith("+") or line.startswith("+++"):
            continue
        content = line[1:]
        if not content.strip():
            continue
        for pattern, marker, _replacement in _COMPILED:
            if pattern.search(content):
                stripped = content.strip()
                is_comment = stripped.startswith(_COMMENT_PREFIXES)
                hits.append(
                    {
                        "file": current_file,
                        "line": stripped[:200],
                        "marker": marker,
                        "is_comment": is_comment,
                    }
                )
                break
    return hits


def strip_comment_hits(hits: list[dict], files: dict[str, list[str]]) -> list[dict]:
    """Remove whole-line comments that contain leak markers.

    `files` maps a path to its lines; it is modified in place. Only comment
    lines are removed - anything in real code is left alone for a human to see.
    """
    removed: list[dict] = []
    for hit in hits:
        if not hit["is_comment"]:
            continue
        target = hit["line"].strip()
        path = hit.get("file")
        candidates = [path] if path in files else list(files)
        for candidate in candidates:
            lines = files.get(candidate)
            if lines is None:
                continue
            kept = [line for line in lines if line.strip() != target]
            if len(kept) != len(lines):
                files[candidate] = kept
                removed.append({"file": candidate, "line": target})
                break
    return removed

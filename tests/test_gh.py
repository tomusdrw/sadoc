from unittest.mock import Mock

import pytest

from sadoc import sanitize
from sadoc.gh import Gh


@pytest.mark.parametrize(
    ("body", "public_body"),
    [
        (
            "Updates dependencies.\n\n- Update:\n  - Refresh the lockfile.\n\n<sub>ref 123</sub>\n",
            "Updates dependencies.\n\n- Update:\n  - Refresh the lockfile.\n\n<sub>ref 123</sub>",
        ),
        (
            "The default branch is failing.\n\n```\n  ERROR: build failed\n```",
            "The default branch is failing.\n\n```\n  ERROR: build failed\n```",
        ),
        (
            "Dependency updates are managed centrally.\n\nGenerated by AI",
            "Dependency updates are managed centrally.",
        ),
    ],
    ids=["dependency-update", "ci-repair", "scrubbed-prose"],
)
def test_open_pr_signs_the_published_body(monkeypatch, body, public_body):
    monkeypatch.setattr("sadoc.gh.shutil.which", lambda binary: binary)
    url = "https://github.com/owner/repo/pull/123"
    run = Mock(return_value=url + "\n")
    monkeypatch.setattr(Gh, "run", run)

    result = Gh().open_pr("owner", "repo", "Update dependencies", body, "update", "main")

    args = run.call_args.args
    published_body, signature = args[args.index("--body") + 1].rsplit("\n\n", 1)
    assert signature == "Opened by [Sadoc](https://github.com/tomusdrw/sadoc)."
    assert published_body == public_body
    assert not sanitize.contains_leak(published_body)
    assert result["url"] == url
